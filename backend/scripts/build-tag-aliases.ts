// One-off: build backend/scraper/tag-aliases.json by joining each old-DB genre
// id against DLsite's CURRENT name for that genre.
//
// The current name is read from the per-genre search page title:
//   https://www.dlsite.com/maniax/fsr/=/genre/<NNN>/
//   <title>「<current ja name>」の作品一覧 | DLsite ...
// This works for ALL genres — including "shadow tags" DLsite removed from the
// public genre-list page (レイプ, 調教, 奴隷, …) but still applies to works. The
// genre-list page cannot see shadow tags; the per-genre search page can.
//
// REQUIRES YOUR PROXY (these pages are region-blocked). Run this script in an
// environment where the scraper's configured proxy (config.ts / HTTPS_PROXY)
// is reachable:
//
//   cd backend && node scripts/build-tag-aliases.ts
//
// It fetches ~300 pages sequentially (one per old-DB genre) with a small delay
// to stay polite. Output: scraper/tag-aliases.json — only entries where the
// current name differs from the old name (the renames). Unchanged genres need
// no entry (canonicalizeTagName passes them through unchanged).
//
// Re-runnable: MERGES with the existing file, so hand-added entries (e.g. the
// katakana ツルペタ → ロリ fold, which no rename produces) survive. A key this
// run regenerated wins; a key it did not is kept as-is. Delete the JSON file
// to regenerate from scratch.

import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import axios from '../scraper/axios.ts'; // proxy-aware, with retry

const OLD_DB = path.join(import.meta.dirname, '..', 'database', 'old_tag_id.sqlite3');
const SEARCH_URL = (id: number) => `https://www.dlsite.com/maniax/fsr/=/genre/${String(id).padStart(3, '0')}/`;

function getOldIdToName(): Map<number, string> {
  const rows = execSync(`sqlite3 "${OLD_DB}" "SELECT id, name FROM t_tag;"`, { encoding: 'utf8' });
  const map = new Map<number, string>();
  for (const line of rows.trim().split('\n')) {
    if (!line) continue;
    const [id, ...nameParts] = line.split('|');
    map.set(parseInt(id, 10), nameParts.join('|').trim());
  }
  return map;
}

// Extract the current genre name from the search page title: 「<name>」の作品一覧
function extractGenreName(html: string): string | null {
  const m = html.match(/「([^」]+)」の作品一覧/);
  return m ? m[1] : null;
}

async function fetchCurrentName(id: number, retryLeft = 3): Promise<string | null> {
  try {
    const resp = await axios.retryGet<string>(SEARCH_URL(id), { retry: {} });
    const name = extractGenreName(resp.data);
    return name;
  } catch (err) {
    if (retryLeft > 0) {
      await new Promise(r => setTimeout(r, 1000));
      return fetchCurrentName(id, retryLeft - 1);
    }
    return null; // genre dead / page gone → no rename
  }
}

(async () => {
  const oldMap = getOldIdToName();
  console.log(`Old DB: ${oldMap.size} genres. Fetching current names from DLsite (needs proxy)...`);

  const aliases: Record<string, string> = {};
  let renamed = 0, same = 0, dead = 0;
  const ids = [...oldMap.keys()].sort((a, b) => a - b);

  for (let i = 0; i < ids.length; i++) {
    const id = ids[i];
    // Every id came from a key of oldMap, so both lookups are present.
    const oldName = oldMap.get(id) as string;
    const curName = await fetchCurrentName(id);
    if (curName === null) {
      dead++;
      console.log(`  [${i + 1}/${ids.length}] id=${id}  DEAD (no search page)  old="${oldName}"`);
    } else if (curName !== oldName) {
      aliases[curName] = oldName;
      renamed++;
      console.log(`  [${i + 1}/${ids.length}] id=${id}  RENAME  "${oldName}" → "${curName}"`);
    } else {
      same++;
      if (process.env.VERBOSE) console.log(`  [${i + 1}/${ids.length}] id=${id}  same  "${oldName}"`);
    }
    await new Promise(r => setTimeout(r, 250)); // be polite
  }

  console.log(`\n  same=${same}  renamed=${renamed}  dead=${dead}  total=${ids.length}`);

  const outPath = path.join(import.meta.dirname, '..', 'scraper', 'tag-aliases.json');

  // Keep hand-added entries this run did not regenerate (see header).
  let existing: Record<string, string> = {};
  try {
    // The file holds one JSON string per key, plus the `_comment` marker.
    const stored = JSON.parse(fs.readFileSync(outPath, 'utf8')) as Record<string, string>;
    for (const [k, v] of Object.entries(stored)) {
      if (!k.startsWith('_')) existing[k] = v;
    }
  } catch { /* no file yet — first run */ }
  const kept = Object.keys(existing).filter(k => !(k in aliases));

  const out = {
    _comment: 'DLsite genre rename map. "new_ja_name": "canonical_old_ja_name". Auto-generated by scripts/build-tag-aliases.ts from old_tag_id.sqlite3 + per-genre search page titles (maniax/fsr/=/genre/NNN/), plus hand-added entries (preserved on regeneration). Edit and restart server to apply.',
    ...aliases,
    ...Object.fromEntries(kept.map(k => [k, existing[k]])),
  };
  fs.writeFileSync(outPath, JSON.stringify(out, null, 2) + '\n');
  console.log(`\nWrote ${renamed} aliases (+${kept.length} kept) to ${outPath}`);
})().catch((err: unknown) => {
  console.error('Failed:', (err as Error).message);
  process.exit(1);
});
